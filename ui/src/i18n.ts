export type MessageKey = keyof typeof messages.ru

export const locale = ref<Language>('ru')

export function setLocale(language: Language) {
  locale.value = language
  document.documentElement.lang = language
}

export function t(key: MessageKey, params?: Params): string {
  const table = messages[locale.value] as Record<string, string>
  const template = table[key] ?? String(key)
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  )
}

type PluralBase =
  | 'processes.count'
  | 'processes.appsCount'
  | 'processes.processesCount'
  | 'processes.instances'
  | 'overview.processCount'
  | 'network.connected'
  | 'cpu.coresCount'
  | 'alerts.rulesCount'

export function pluralForm(count: number): 'one' | 'few' | 'many' {
  const absolute = Math.abs(count) % 100
  const last = absolute % 10
  if (absolute > 10 && absolute < 20) return 'many'
  if (last === 1) return 'one'
  if (last >= 2 && last <= 4) return 'few'
  return 'many'
}

/// Russian needs three plural forms; English gets by with one/many.
export function tn(base: PluralBase, count: number, extra?: Params): string {
  const form = locale.value === 'ru' ? pluralForm(count) : count === 1 ? 'one' : 'many'
  return t(`${base}.${form}` as MessageKey, { n: count, ...extra })
}

export function localeCode() {
  return locale.value === 'ru' ? 'ru-RU' : 'en-US'
}

export function formatTime(ms: number) {
  return new Date(ms).toLocaleTimeString(localeCode())
}

export function formatBytes(value: number): string {
  if (value >= 1024 ** 3) return `${(value / 1024 ** 3).toFixed(1)} ${t('unit.gb')}`
  if (value >= 1024 ** 2) return `${Math.round(value / 1024 ** 2)} ${t('unit.mb')}`
  if (value >= 1024) return `${Math.round(value / 1024)} ${t('unit.kb')}`
  return `${value} ${t('unit.b')}`
}

export function formatRate(value: number): string {
  if (value >= 1024 ** 2) return `${(value / 1024 ** 2).toFixed(1)} ${t('unit.mbps')}`
  if (value >= 1024) return `${Math.round(value / 1024)} ${t('unit.kbps')}`
  return `${value} ${t('unit.bps')}`
}

export function formatDuration(seconds: number): string {
  return seconds >= 60
    ? `${Math.round(seconds / 60)} ${t('unit.min')}`
    : `${seconds} ${t('unit.sec')}`
}
